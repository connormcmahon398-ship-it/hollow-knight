/**
 * @param {string} shape
 * @returns {RoomTemplate[]}
 */
export function templatesOfShape(shape) {
  return TEMPLATES.filter((t) => t.shape === shape);
}

/**
 * Templates that a player with the given tag capabilities can complete.
 * @param {Set<string>} available e.g. {'jump','wall','break'}
 * @returns {RoomTemplate[]}
 */
export function templatesRequiring(available) {
  const gating = ['wall', 'break', 'swim', 'aerial'];
  return TEMPLATES.filter((t) => t.tags.every((tag) => !gating.includes(tag) || available.has(tag)));
}
