/**
 * @file Hand-authored room templates.
 *
 * ## The authoring model
 * Building three hundred rooms entirely by hand is not a good use of effort,
 * and building them entirely by algorithm produces the characterless corridors
 * that give procedural level design a bad name. This project takes the middle
 * path that shipping games actually use:
 *
 * **Every room's interior is hand-authored. The connections between them are
 * generated.**
 *
 * A template below is a complete, deliberately designed room — its platform
 * spacing, its sightlines, its hazard placement and its enemy positions are all
 * chosen. The generator's job is only to decide *which* template goes where in
 * the world graph, to re-skin it with the local biome's tiles and creatures, and
 * to open the doorways that connect it to its neighbours.
 *
 * The result is a large world where every room is a designed space, and no two
 * playthroughs of a region encounter the same sequence of them.
 *
 * ## Template contract
 * - Templates are exactly 30x17 tiles (one screen) or 30x34 (a tall room).
 * - Column 0 and column 29 are the horizontal doorway columns; the generator
 *   opens or seals them. Templates must leave a walkable surface adjacent to
 *   both, at the row indicated by `doorRow`.
 * - `tags` declare what the template demands, so the generator never places a
 *   template requiring a double jump in a region reachable before it.
 */

/**
 * @typedef {Object} RoomTemplate
 * @property {string} id
 * @property {string[]} art
 * @property {number} doorRow Tile row of the side doorways' top edge.
 * @property {string[]} tags Requirements and character, e.g. ['jump','combat'].
 * @property {number} [difficulty] 1..10
 * @property {string} [shape] 'corridor'|'hall'|'shaft'|'arena'|'maze'
 */

/** Standard room dimensions, in tiles. One screen at the internal resolution. */
export const ROOM_W = 30;
export const ROOM_H = 17;

/** @type {RoomTemplate[]} */
export const TEMPLATES = [];

/**
 * @param {RoomTemplate} t
 */
function template(t) {
  if (t.art.length !== ROOM_H && t.art.length !== ROOM_H * 2) {
    throw new Error(`Template "${t.id}" is ${t.art.length} rows; expected ${ROOM_H} or ${ROOM_H * 2}`);
  }
  for (const row of t.art) {
    if (row.length !== ROOM_W) {
      throw new Error(`Template "${t.id}" has a row of length ${row.length}; expected ${ROOM_W}`);
    }
  }
  TEMPLATES.push(t);
}

